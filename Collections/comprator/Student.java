package Collections.comprator;

public class Student {
    int marks;
    String name;
    int age;

    Student(int marks,String name, int age){
        this.marks = marks;
        this.name = name;
        this.age = age;
    }

    public int getMarks() {
        return marks;
    }

    public String getName() {
        return name;
    }

    public int getAge() {
        return age;
    }
}
